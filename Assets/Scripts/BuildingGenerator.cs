using System;
using System.Collections.Generic;
using System.Text;
using UnityEngine;
using static TerrainMath;

/// <summary>
/// PHASE 5 — core building generation system. Creates basic building data from SettlementMap massing data.
/// This system focuses on generating the core building attributes (position, orientation, footprint, floors, household type)
/// that can be used by other systems for detailed building construction (exterior, interior, etc.).
/// Follows the same pattern as other Phase systems.
/// </summary>
public static class BuildingGenerator
{
    /// <summary>
    /// Core building data generated by this system.
    /// </summary>
    public class BuildingData
    {
        public int id;                    // unique building identifier
        public int lot;                   // owning lot index (ZoneMap.Lots)
        public int settlement;            // owning settlement index
        public string householdType;      // "farmer", "fisher", "shopkeeper", etc.
        public Vector3 position;          // building base position
        public float yaw;                 // building orientation (radians)
        public int floors;                // number of floors (1-3)
        public Vector2 footprint;         // building footprint (width, depth)
    }

    // ---- state ----
    public static readonly List<BuildingData> Buildings = new List<BuildingData>();
    public static bool Built;
    public static string Report = "";
    static int Hash;

    // ---- configuration ----
    // No additional configuration needed for core generation; uses SettlementMap and ArchitecturalKit

    // ---- main build ----
    /// <summary>
    /// Generates core building data from SettlementMap massing.
    /// Dependencies: ZoneMap (3.9) -> SettlementMap (4.3) -> PadGrade (4.4) -> LaneNet (4.5) ->
    /// WaterAccess (4.6) -> FarmPlots (4.7) -> ArchitecturalKit (5.0) -> BuildingGenerator (5.0 core)
    /// </summary>
    public static void Build()
    {
        // Dependencies: ensure SettlementMap and ArchitecturalKit are built
        if (!SettlementMap.Built) SettlementMap.Build();
        if (!ArchitecturalKit.Built) ArchitecturalKit.Build();

        Buildings.Clear();

        GenerateCoreBuildings();

        unchecked
        {
            int hs = (int)2166136261u;
            hs = (hs ^ Buildings.Count) * 16777619;
            foreach (var b in Buildings)
            {
                hs = (hs ^ b.id) * 16777619;
                hs = (hs ^ (int)(b.position.x * 1000f)) * 16777619;
                hs = (hs ^ (int)(b.position.z * 1000f)) * 16777619;
                hs = (hs ^ b.floors) * 16777619;
            }
            Hash = hs;
        }

        Built = true;
        Validate();
    }

    /// <summary>
    /// Clears all generated building data and resets the build state.
    /// </summary>
    public static void Clear()
    {
        Buildings.Clear();
        Built = false;
        Report = "";
        Hash = 0;
    }

    // ---- debugging ----
    /// <summary>
    /// Forces a rebuild and returns the validation report (for debugging placement issues).
    /// </summary>
    public static string RebuildAndValidate()
    {
        Built = false;
        Build();
        return Validate();
    }

    // ---- generate core buildings from settlement massing data ----
    static void GenerateCoreBuildings()
    {
        // Create one building per lot in SettlementMap
        for (int li = 0; li < SettlementMap.Lots.Length; li++)
        {
            var massing = SettlementMap.Lots[li];
            if (massing.dropped) continue; // skip duplicate lots

            // Determine household type based on settlement and zone
            string householdType = DetermineHouseholdType(massing.settlement, li);

            Buildings.Add(new BuildingData
            {
                id = Buildings.Count,
                lot = li,
                settlement = massing.settlement,
                householdType = householdType,
                position = new Vector3((float)massing.x, TerrainMath.Hm((float)massing.x, (float)massing.z), (float)massing.z),
                yaw = massing.yaw,
                floors = massing.floors,
                footprint = new Vector2(massing.footprintW, massing.footprintD)
            });
        }
    }

    // ---- determine household type based on settlement/zone ----
    static string DetermineHouseholdType(int settlementIndex, int lotIndex)
    {
        if (settlementIndex < 0 || settlementIndex >= SettlementMap.Settlements.Count)
            return "farmer"; // default fallback

        var settlement = SettlementMap.Settlements[settlementIndex];

        // Based on settlement role and nearby features
        switch (settlement.role)
        {
            case Zone.Harbour:
                // Harbour settlements: mix of fishers and shopkeepers
                return lotIndex % 3 == 0 ? "fisher" :
                       lotIndex % 3 == 1 ? "shopkeeper" : "farmer";
            case Zone.Farm:
                // Farm settlements: primarily farmers
                return "farmer";
            case Zone.Hamlet:
                // Hamlet settlements: mixed farming and trades
                return lotIndex % 4 == 0 ? "shopkeeper" : "farmer";
            case Zone.Summit:
                // Summit settlements: specialized/fewer households
                return "farmer"; // or potentially hermit/monk
            default:
                return "farmer";
        }
    }

    // ---- validation (5.0) ----
    public static string Validate()
    {
        if (!Built) Build();
        var sb = new StringBuilder("[BuildingGenerator 5.0 Core]\n");
        var fails = new List<string>(); int pass = 0;

        int totalBuildings = Buildings.Count;
        int buildingsWithoutLot = 0;
        int buildingsInvalidFloors = 0;
        int buildingsZeroFootprint = 0;

        // Validate each building
        foreach (var building in Buildings)
        {
            // Check lot assignment
            if (building.lot < 0 || building.lot >= ZoneMap.Lots.Count)
                buildingsWithoutLot++;

            // Check floors (should be 1-3 per SettlementMap)
            if (building.floors < 1 || building.floors > 3)
                buildingsInvalidFloors++;

            // Check footprint (should have positive area)
            if (building.footprint.x <= 0.1f || building.footprint.y <= 0.1f)
                buildingsZeroFootprint++;
        }

        if (buildingsWithoutLot == 0)
            pass++; else fails.Add(buildingsWithoutLot + " buildings have invalid lot assignments");

        if (buildingsInvalidFloors == 0)
            pass++; else fails.Add(buildingsInvalidFloors + " buildings have invalid floor count (outside 1-3 range)");

        if (buildingsZeroFootprint == 0)
            pass++; else fails.Add(buildingsZeroFootprint + " buildings have invalid footprint (zero or negative dimensions)");

        // Check determinism: generate buildings twice and see if we get the same hash
        int hash1 = Hash;
        int hash2 = 0;
        int hash3 = 0;

        // First generation
        Buildings.Clear();
        GenerateCoreBuildings();
        unchecked
        {
            int hs = (int)2166136261u;
            hs = (hs ^ Buildings.Count) * 16777619;
            foreach (var b in Buildings)
            {
                hs = (hs ^ b.id) * 16777619;
                hs = (hs ^ (int)(b.position.x * 1000f)) * 16777619;
                hs = (hs ^ (int)(b.position.z * 1000f)) * 16777619;
                hs = (hs ^ b.floors) * 16777619;
            }
            hash2 = hs;
        }

        // Second generation
        Buildings.Clear();
        GenerateCoreBuildings();
        unchecked
        {
            int hs = (int)2166136261u;
            hs = (hs ^ Buildings.Count) * 16777619;
            foreach (var b in Buildings)
            {
                hs = (hs ^ b.id) * 16777619;
                hs = (hs ^ (int)(b.position.x * 1000f)) * 16777619;
                hs = (hs ^ (int)(b.position.z * 1000f)) * 16777619;
                hs = (hs ^ b.floors) * 16777619;
            }
            hash3 = hs;
        }

        bool det = (hash2 == hash3);
        if (det) pass++; else fails.Add("core building generation is not deterministic");

        sb.AppendLine("buildings " + totalBuildings + " | lots processed " + ZoneMap.Lots.Count);
        sb.AppendLine("buildings with invalid lot: " + buildingsWithoutLot + "/" + totalBuildings);
        sb.AppendLine("buildings with invalid floors: " + buildingsInvalidFloors + "/" + totalBuildings);
        sb.AppendLine("buildings with invalid footprint: " + buildingsZeroFootprint + "/" + totalBuildings);
        sb.AppendLine("RULES (5.0 Core): " + pass + " pass / " + fails.Count + " fail");
        foreach (var f in fails) sb.AppendLine("  FAIL: " + f);
        Report = sb.ToString();
        return Report;
    }

    #if UNITY_EDITOR
    [UnityEditor.MenuItem("Island/Phase 5.0 Core Building Generator + Validate")]
    static void Menu() { Built = false; Build(); Debug.Log(Validate()); }
    #endif
}