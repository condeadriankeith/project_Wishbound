using System;
using System.Collections.Generic;
using UnityEngine;

// Data model for Phases 3-4 (water, roads, zoning, settlements, farms).
// Everything is in world metres, Y up. yaw (deg): forward = (sin yaw, cos yaw) in (x, z).

[Serializable] public class PlanRiver { public Vector3[] pts; public float[] flow; public int joinsExisting; }
[Serializable] public class PlanFall { public Vector3 rim, pool; public float drop; public int river; }
[Serializable] public class PlanRoad { public string name; public Vector3[] pts; public float length, maxGrade, meanGrade; public Vector3[] bridges; }
[Serializable] public class PlanSettlement { public string name; public int kind; public int level; public Vector3 center; public float plazaR; }   // kind: 0 harbour town, 1 farm village, 2 hamlet, 3 summit tower
[Serializable] public class PlanHouse { public int settlement; public Vector3 pos; public float yaw; public Vector2 size; public Vector3 door, laneEnd; public int plot = -1; public float waterDist, laneGrade; }
[Serializable] public class PlanPlot { public int house; public Vector3 center; public float yaw, relief; public Vector2 size; }
[Serializable] public class PlanWell { public int settlement; public Vector3 pos; }

[Serializable]
public class WorldPlanData
{
    public int seed;
    public Vector3 lake;
    public List<PlanRiver> rivers = new List<PlanRiver>();
    public List<PlanFall> falls = new List<PlanFall>();
    public List<PlanRoad> roads = new List<PlanRoad>();
    public List<PlanSettlement> settlements = new List<PlanSettlement>();
    public List<PlanHouse> houses = new List<PlanHouse>();
    public List<PlanPlot> plots = new List<PlanPlot>();
    public List<PlanWell> wells = new List<PlanWell>();
    public List<string> report = new List<string>();
}

/// Scene-view preview of the plan. Generated by Tools > Island > 5. Generate World Plan.
public class WorldPlanGizmos : MonoBehaviour
{
    public WorldPlanData data = new WorldPlanData();
    public bool showRivers = true, showRoads = true, showSettlements = true, showPlots = true;

    static void Line(Vector3[] pts, float lift)
    {
        if (pts == null) return;
        for (int i = 0; i + 1 < pts.Length; i++)
            Gizmos.DrawLine(pts[i] + Vector3.up * lift, pts[i + 1] + Vector3.up * lift);
    }

    void OnDrawGizmos()
    {
        if (data == null) return;
        var m0 = Gizmos.matrix;

        if (showRivers)
        {
            Gizmos.color = new Color(0.25f, 0.65f, 1f);
            foreach (var r in data.rivers) Line(r.pts, 0.4f);
            Gizmos.color = Color.white;
            foreach (var f in data.falls) { Gizmos.DrawLine(f.rim, f.pool); Gizmos.DrawWireSphere(f.pool, 4f); }
            Gizmos.color = Color.cyan;
            if (data.lake != Vector3.zero) Gizmos.DrawWireSphere(data.lake, 9f);
        }
        if (showRoads)
        {
            Gizmos.color = new Color(1f, 0.55f, 0.1f);
            foreach (var r in data.roads) Line(r.pts, 0.6f);
            Gizmos.color = Color.magenta;
            foreach (var r in data.roads) if (r.bridges != null) foreach (var b in r.bridges) Gizmos.DrawWireCube(b + Vector3.up, new Vector3(6, 2, 6));
        }
        if (showSettlements)
        {
            foreach (var s in data.settlements)
            {
                Gizmos.color = s.kind == 0 ? Color.red : s.kind == 1 ? new Color(1f, 0.8f, 0.2f) : s.kind == 2 ? new Color(0.9f, 0.6f, 0.9f) : Color.white;
                Gizmos.matrix = Matrix4x4.TRS(s.center + Vector3.up * 0.5f, Quaternion.identity, new Vector3(1, 0.02f, 1));
                Gizmos.DrawWireSphere(Vector3.zero, s.plazaR);
                Gizmos.matrix = m0;
            }
            foreach (var h in data.houses)
            {
                Gizmos.color = new Color(0.95f, 0.9f, 0.8f);
                Gizmos.matrix = Matrix4x4.TRS(h.pos + Vector3.up * 2f, Quaternion.Euler(0, h.yaw, 0), new Vector3(h.size.x, 4f, h.size.y));
                Gizmos.DrawWireCube(Vector3.zero, Vector3.one);
                Gizmos.matrix = m0;
                Gizmos.color = new Color(0.6f, 0.45f, 0.3f);
                Gizmos.DrawLine(h.door + Vector3.up * 0.3f, h.laneEnd + Vector3.up * 0.3f);
            }
            Gizmos.color = Color.cyan;
            foreach (var w in data.wells) Gizmos.DrawWireSphere(w.pos + Vector3.up, 1.2f);
        }
        if (showPlots)
        {
            Gizmos.color = new Color(0.4f, 0.9f, 0.3f);
            foreach (var p in data.plots)
            {
                Gizmos.matrix = Matrix4x4.TRS(p.center + Vector3.up * 0.5f, Quaternion.Euler(0, p.yaw, 0), new Vector3(p.size.x, 0.2f, p.size.y));
                Gizmos.DrawWireCube(Vector3.zero, Vector3.one);
                Gizmos.matrix = m0;
            }
        }
        Gizmos.matrix = m0;
    }
}
